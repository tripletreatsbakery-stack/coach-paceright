// Reuse the verified SQL calculations without referencing or granting private views.
// The generated function executes with the caller's existing table permissions/RLS.
import {readFileSync,writeFileSync} from 'node:fs';
const sql=readFileSync('database/coach-portal.sql','utf8').replaceAll('\r\n','\n');
const races=sql.split('create or replace view coach_private.races as\n')[1].split(';')[0];
const roster=sql.split('create or replace view coach_private.roster as\n')[1].split(';')[0].replaceAll('coach_private.races','races');
const result=sql.split('return jsonb_build_object(')[1].split(');')[0].replaceAll('coach_private.roster','roster').replaceAll('coach_private.races','races');
if(!races||!roster||!result)throw Error('Source SQL layout changed; inspect before generating.');
writeFileSync('database/public-dashboard.sql',`-- Generated by scripts/generate-public-dashboard.mjs from the verified coach SQL.
-- Only already-public source data; no private schema access or elevated privileges.
begin;
create or replace function public.coach_public_dashboard() returns jsonb
language sql stable security invoker set search_path='' as $$
with races as (${races}), roster as (${roster})
select jsonb_build_object(${result});
$$;
revoke all on function public.coach_public_dashboard() from public;
grant execute on function public.coach_public_dashboard() to anon,authenticated;
commit;
`);
